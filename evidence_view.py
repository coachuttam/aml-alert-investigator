"""The computed findings and the evidence table for one alert (Streamlit part).

Each finding can be opened to see the transactions behind it, and the evidence table
marks every row that any finding cites. Kept apart from app.py so each file stays short.
"""
from __future__ import annotations

from typing import Dict, List, Tuple

import pandas as pd
import streamlit as st

from src.evidence import cited_ids
from src.money import format_rupees

TABLE_HEIGHT = 320     # pixels: tall enough for about nine rows before it scrolls


def show_table(table: pd.DataFrame, **options) -> None:
    """A full-width table. Newer Streamlit says width="stretch"; older versions say use_container_width."""
    try:
        st.dataframe(table, width="stretch", hide_index=True, **options)
    except (TypeError, ValueError):
        st.dataframe(table, use_container_width=True, hide_index=True, **options)


def signed_amount(txn: dict) -> str:
    """+ for money in, − for money out."""
    sign = "+" if txn["direction"] == "credit" else "−"
    return f"{sign}{format_rupees(txn['amount'])}"


def row_for_table(txn: dict) -> dict:
    """The columns shown for one transaction."""
    return {"Date": txn["day"], "Channel": txn["channel"], "Amount": signed_amount(txn),
            "Counterparty": txn["counterparty"]}


def show_findings(findings: List[Tuple[str, List[str]]], transactions: List[dict]) -> None:
    """Each computed finding; one with rows behind it opens to list them."""
    st.markdown("**Computed findings**")
    by_id: Dict[str, dict] = {txn["txn_id"]: txn for txn in transactions}
    for text, ids in findings:
        if not ids:
            st.markdown(f"- {text}")
            continue
        with st.expander(f"{text}  ·  {len(ids)} rows"):
            rows = sorted((by_id[i] for i in ids if i in by_id), key=lambda txn: txn["day"])
            show_table(pd.DataFrame([row_for_table(txn) for txn in rows]))


def show_evidence(findings: List[Tuple[str, List[str]]], transactions: List[dict]) -> None:
    """All transactions, with a mark on every row that a finding cites."""
    if not transactions:
        st.caption("Transactions are not available here (the raw file is generated by `python -m src.generator`).")
        return
    cited = cited_ids(findings)
    rows = []
    for txn in sorted(transactions, key=lambda t: t["day"]):
        rows.append({"Evidence": "●" if txn["txn_id"] in cited else "", **row_for_table(txn)})
    st.caption("● marks rows that a computed finding above points at.")
    show_table(pd.DataFrame(rows), height=TABLE_HEIGHT)
